#!/usr/bin/env python3
"""Provenance of bodies/ssl_robot/model.xml: there is no upstream model. No SSL team publishes a URDF or MJCF; the
TIGERs Mannheim v2020 CAD (github.com/TIGERs-Mannheim/mechanics) is under a custom non-commercial licence and
ER-Force's CAD carries no licence, so none of it is used. body.py builds the robot from the published dimensions in
body.toml [geometry] (each with its source) as simple solids: convex prisms for the chassis (a 178 mm cylinder cut
flat at the front, with the dribbler opening), a 14 mm cylinder for the dribbling bar on a hinged carrier, a box
for the chip shovel / kicker face, thin discs for the vision pattern.

This tool writes model.xml: one robot (blue, id 0) at the origin, in a world with nothing else, from body.py's
mount() (the same code every scene uses). Run after any change of body.py or body.toml:

    python bodies/ssl_robot/tools/make_model.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))


def main():
    import mujoco as mj
    from bodies.ssl_robot import body as SSL
    spec = mj.MjSpec()
    spec.modelname = "ssl_robot"
    spec.option.timestep = 0.001
    SSL.mount(spec, "robot", "blue", 0, pose=(0.0, 0.0, 0.0))
    spec.compile()
    out = Path(__file__).resolve().parents[1] / "model.xml"
    xml = spec.to_xml()
    head = "<!-- generated by bodies/ssl_robot/tools/make_model.py from body.py + body.toml; do not edit -->\n"
    out.write_text(head + xml)
    print(f"wrote {out} ({len(xml)} bytes)")


if __name__ == "__main__":
    main()
