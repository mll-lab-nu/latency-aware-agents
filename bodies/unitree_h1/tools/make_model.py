#!/usr/bin/env python3
"""Provenance of the Unitree H1 body (bodies/unitree_h1/): Unitree's own MJCF of the H1-2 (the H1 revision with 6-DOF
legs and 7-DOF arms), unitree_rl_gym resources/robots/h1_2/h1_2.xml (BSD-3-Clause) -> model.xml (the template body.py
reads), meshes_fine/ (Unitree's meshes, unchanged; 39 MB, not in git: this script regenerates them) and meshes/
(decimated copies for the simulation, the players' cameras and in-task videos).

    python tools/make_model.py UNITREE_RL_GYM_DIR COMMIT       (needs mujoco, numpy, trimesh, fast-simplification;
                                                              not in the image)

Changes against Unitree's h1_2.xml (also listed in body.toml and the design note):
  hands      the Inspire dexterous hands keep their meshes but lose their 24 finger joints (the fingers are rigid, open)
             and their finger collision; the palm's collision mesh stays; a wrist mount on each hand (body <side>_mount
             in the palm, +z along the fingers) carries a bodies/hands tool;
  actuators  Unitree's motors (one per joint, no gains) and the finger motors are dropped; body.py adds one torque
             motor per joint at the URDF effort limits; the legs get torques from the walking policy's PD (or the
             kick), the torso and the arms from the body's servo;
  joints     every joint gets the defaults of Unitree's own sim-to-sim model h1_2_12dof.xml (damping 0.001, armature
             0.01, frictionloss 0.1), the model the walking policy was validated on in MuJoCo;
  collision  Unitree's collision geoms become robot geoms (contype 4, conaffinity 0: they touch the ball, a table, a
             net, never the robot itself), except the ankle-roll (foot) meshes, which keep touching the floor (contype
             1, conaffinity 1: the floor contact the policy was validated with); the torso's small box and the
             pelvis sphere are replaced by the torso and pelvis meshes (convex hulls); one box under each foot
             (contype 8) touches only a ball that carries conaffinity bit 8 (a soccer ball);
  look       two materials (dark and metal grey) instead of Unitree's uniform rgba 0.1, the logo white;
  cameras    a stereo head camera (two cameras 5 cm apart, 58 degree vertical field of view: the H1 head's Intel
             RealSense D435i class depth camera; its tilt is a mount parameter); sensors, statistic dropped.
"""
from __future__ import annotations

import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parents[1]
DECIMATE = 0.065                       # 787 k faces -> 58 k
METAL = ("hip_pitch", "knee", "shoulder_roll", "elbow_pitch")


def decimate(src: Path, dst: Path):
    import fast_simplification
    import trimesh
    m = trimesh.load(src, force="mesh", process=True)
    target = max(200, int(len(m.faces) * DECIMATE))
    if len(m.faces) > target:
        v2, f2 = fast_simplification.simplify(np.asarray(m.vertices, np.float32), np.asarray(m.faces, np.int32),
                                              target_reduction=1.0 - target / len(m.faces))
        m = trimesh.Trimesh(v2, f2, process=True)
    dst.parent.mkdir(parents=True, exist_ok=True)
    m.export(dst)
    return len(m.faces)


def main(src_root: str, commit: str):
    src_dir = Path(src_root) / "resources" / "robots" / "h1_2"
    root = ET.parse(src_dir / "h1_2.xml").getroot()
    fine, coarse = HERE / "meshes_fine", HERE / "meshes"
    for d in (fine, coarse):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir()
    asset = root.find("asset")
    nf = 0
    for m in asset.findall("mesh"):
        f = m.get("file")
        shutil.copy2(src_dir / "meshes" / f, fine / f)
        nf += decimate(src_dir / "meshes" / f, coarse / (Path(f).stem + ".stl"))
        m.set("file", Path(f).stem + ".stl")
        m.set("name", "h1_" + m.get("name"))
    for n, rgba in (("dark", "0.13 0.13 0.14 1"), ("metal", "0.62 0.63 0.66 1"), ("white", "0.92 0.92 0.92 1")):
        ET.SubElement(asset, "material", name=f"h1_m_{n}", rgba=rgba, specular="0.4", shininess="0.4")
    shutil.copy2(Path(src_root) / "LICENSE", HERE / "LICENSE")
    for tag in ("actuator", "sensor", "keyframe", "option", "statistic", "default"):
        for el in root.findall(tag):
            root.remove(el)
    root.set("model", "unitree_h1")
    comp = root.find("compiler")
    comp.set("meshdir", "meshes")
    comp.set("autolimits", "true")
    root.insert(0, ET.Comment(
        f" Generated by bodies/unitree_h1/tools/make_model.py from Unitree unitree_rl_gym resources/robots/h1_2/h1_2.xml "
        f"(commit {commit}, BSD-3-Clause, LICENSE; Unitree H1-2: 6-DOF legs, a torso joint, 7-DOF arms, Inspire hands "
        "with rigid fingers). Template of the RoboOlympics Unitree H1 body: read by body.py, which prefixes every name, "
        "picks the mesh level and mounts the hand and the motors. Do not edit. "))
    default = ET.Element("default")
    top = ET.SubElement(default, "default", {"class": "h1_h1"})
    ET.SubElement(top, "joint", damping="0.001", armature="0.01", frictionloss="0.1")
    ET.SubElement(top, "site", rgba="1 0 0 1", size="0.01", group="5")
    vis = ET.SubElement(top, "default", {"class": "h1_visual"})
    ET.SubElement(vis, "geom", group="2", type="mesh", contype="0", conaffinity="0", density="0",
                  material="h1_m_dark")
    col = ET.SubElement(top, "default", {"class": "h1_collision"})
    ET.SubElement(col, "geom", group="3", contype="4", conaffinity="0")
    foot = ET.SubElement(col, "default", {"class": "h1_foot"})
    ET.SubElement(foot, "geom", contype="1", conaffinity="1")
    root.insert(2, default)

    wb = root.find("worldbody")
    pelvis = wb.find("body")
    pelvis.set("childclass", "h1_h1")
    for j in pelvis.findall("joint"):                  # the floating base: a plain freejoint (no joint defaults)
        idx = list(pelvis).index(j)
        pelvis.remove(j)
        pelvis.insert(idx, ET.Element("freejoint", name="floating_base_joint"))
    bodies = {b.get("name"): b for b in root.iter("body")}
    parent = {c: p for p in root.iter() for c in p}

    def in_finger(b):
        while b is not None and b.tag == "body":
            n = b.get("name")
            if n[:2] in ("L_", "R_"):
                return True
            b = parent.get(b)
        return False

    for b in list(root.iter("body")):
        name = b.get("name")
        finger = in_finger(b)
        if finger:
            for j in b.findall("joint"):
                b.remove(j)
        for g in list(b.findall("geom")):
            visual = g.get("contype") == "0" and g.get("conaffinity") == "0"
            for a in ("contype", "conaffinity", "group", "density"):
                g.attrib.pop(a, None)
            if g.get("mesh"):
                g.set("mesh", "h1_" + g.get("mesh"))
            if visual:
                g.set("class", "h1_visual")
                g.attrib.pop("type", None)
                g.attrib.pop("rgba", None)
                mesh = g.get("mesh")
                if mesh == "h1_logo_link":
                    g.set("material", "h1_m_white")
                elif any(k in mesh for k in METAL):
                    g.set("material", "h1_m_metal")
                continue
            g.attrib.pop("rgba", None)
            if finger:                                   # the rigid fingers: visual only
                b.remove(g)
            elif name.endswith("ankle_roll_link"):
                g.set("class", "h1_foot")
            elif name in ("torso_link", "pelvis") and g.get("mesh") is None:
                b.remove(g)                              # the small box / sphere: replaced by the meshes below
            else:
                g.set("class", "h1_collision")
    for name, mesh in (("pelvis", "h1_pelvis"), ("torso_link", "h1_torso_link")):
        b = bodies[name]
        idx = max(i for i, c in enumerate(list(b)) if c.tag == "geom") + 1
        b.insert(idx, ET.Element("geom", {"class": "h1_collision", "type": "mesh", "mesh": mesh}))
    for side in ("left", "right"):
        footb = bodies[f"{side}_ankle_roll_link"]
        # the strike box: the foot mesh spans x -0.086 .. 0.174, y +-0.043, z -0.045 .. 0.03 (ankle-roll frame)
        ET.SubElement(footb, "geom", name=f"{side}_foot_strike", type="box", pos="0.044 0 -0.02",
                      size="0.13 0.045 0.028", contype="8", conaffinity="0", group="3", mass="0", density="0",
                      rgba="0.2 0.6 0.9 0.3")
        ET.SubElement(footb, "site", name=f"{side}_foot", pos="0 0 -0.045")
        hand = bodies[f"{side}_wrist_yaw_link"]
        # the palm: the Inspire hand spans x 0.054 .. 0.196 (palm), y +-0.027, and its fingers start at x 0.19 (wrist-yaw
        # frame); the palm faces -y (left hand) / +y (right hand: the thumb's side). The mount sits in front of the
        # palm where the fingers would close around a handle (a shakehand grip): +z along the fingers (the link's +x),
        # +x the palm's normal, so that a paddle's face turns with the wrist yaw (+-1.27 rad) and not only with the
        # narrow wrist pitch (+-0.47 rad)
        sgn = -1.0 if side == "left" else 1.0
        ET.SubElement(hand, "body", name=f"{side}_mount", pos=f"0.15 {0.04 * sgn:.3f} 0",
                      quat="0.5 -0.5 0.5 -0.5" if side == "left" else "0.5 0.5 0.5 0.5")
    torso = bodies["torso_link"]
    # the head (part of the torso mesh, up to z 0.76, the face at x 0.125): the camera pair in front of the face,
    # looking along +x; the tilt is set by body.py (head_pitch); MuJoCo cameras look along their local -z
    head = ET.SubElement(torso, "body", name="head_cam", pos="0.13 0 0.66")
    for cam, y in (("head_left", 0.025), ("head_right", -0.025)):
        ET.SubElement(head, "camera", name=cam, pos=f"0 {y} 0", xyaxes="0 -1 0 0 0 1", fovy="58")
    ET.SubElement(head, "site", name="head_center", size="0.01", group="5")
    ET.indent(root, space="  ")
    (HERE / "model.xml").write_text(ET.tostring(root, encoding="unicode") + "\n")
    print("faces (meshes/):", nf)


if __name__ == "__main__":
    main(*sys.argv[1:3])
